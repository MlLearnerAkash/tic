import Foundation
import AppKit
import CryptoKit

final class ClipboardMonitor {
    private weak var app: AppState?
    private var timer: Timer?
    private var lastChangeCount: Int
    private var suppressNext = false

    private var lastExternalApp: NSRunningApplication?
    private var activationObserver: NSObjectProtocol?

    private static let excludedBundleIDs: Set<String> = [
        "app.tic.menubar",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.apple.SecurityAgent",
        "com.1password.1password",
        "com.1password.1password7",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "com.keepassxc.keepassxc",
        "org.keepassx.keepassxc",
        "com.enpass.Enpass",
        "com.nordpass.NordPass",
        "com.proton.pass",
        "com.protonmail.pass",
        "com.callpod.otp",
        "in.sinew.Enpass-Desktop"
    ]

    private static let privateMarkerFragments: [String] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
        "com.apple.is-sensitive",
        "com.typeit4me.clipping",
        "Pasteboard generator type"
    ]

    init(app: AppState) {
        self.app = app
        let pasteboard = NSPasteboard.general
        self.lastChangeCount = pasteboard.changeCount
        self.lastExternalApp = NSWorkspace.shared.frontmostApplication

        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification,
            object: nil,
            queue: .main
        ) { [weak self] note in
            guard let running = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication else { return }
            self?.noteActivation(running)
        }
    }

    deinit {
        if let activationObserver {
            NSWorkspace.shared.notificationCenter.removeObserver(activationObserver)
        }
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func suppressNextChange() {
        suppressNext = true
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func noteActivation(_ running: NSRunningApplication) {
        let ownBundle = Bundle.main.bundleIdentifier
        if running.bundleIdentifier == ownBundle { return }
        if Self.excludedBundleIDs.contains(running.bundleIdentifier ?? "") { return }
        lastExternalApp = running
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let current = pasteboard.changeCount
        guard current != lastChangeCount else { return }

        lastChangeCount = current
        if suppressNext {
            suppressNext = false
            return
        }

        guard !Self.hasPrivateMarker(pasteboard) else { return }

        let sourceApp = lastExternalApp
        let bundleID = sourceApp?.bundleIdentifier
        if let bundleID, Self.excludedBundleIDs.contains(bundleID) { return }

        let sourceName = sourceApp?.localizedName ?? "Unknown"
        capture(from: pasteboard, sourceApp: sourceName, sourceBundleID: bundleID)
    }

    private static func hasPrivateMarker(_ pasteboard: NSPasteboard) -> Bool {
        let types = pasteboard.types?.map(\.rawValue) ?? []
        return types.contains { type in
            privateMarkerFragments.contains { type.localizedCaseInsensitiveContains($0) }
        }
    }

    private func capture(from pasteboard: NSPasteboard, sourceApp: String, sourceBundleID: String?) {
        // Files win over the icon/text representations that accompany them.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [NSURL],
           !urls.isEmpty {
            let paths = urls.map { ($0 as URL).path }
            let hash = Self.hash(parts: ["file"] + paths)
            let size = paths.reduce(0) { partial, path in
                guard let attrs = try? FileManager.default.attributesOfItem(atPath: path),
                      let fileSize = attrs[.size] as? NSNumber else { return partial }
                return partial + fileSize.intValue
            }
            app?.recordClipboard(
                kind: .file,
                text: nil,
                imageFileName: nil,
                filePaths: paths,
                sourceApp: sourceApp,
                sourceBundleID: sourceBundleID,
                hash: hash,
                byteSize: size
            )
            return
        }

        if let imageData = Self.readImageData(from: pasteboard) {
            guard let name = TicStorage.shared.writeImage(imageData) else { return }
            let hash = Self.hash(data: imageData)
            app?.recordClipboard(
                kind: .image,
                text: nil,
                imageFileName: name,
                filePaths: [],
                sourceApp: sourceApp,
                sourceBundleID: sourceBundleID,
                hash: hash,
                byteSize: imageData.count
            )
            return
        }

        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        let kind = Self.classify(text)
        let hash = Self.hash(parts: ["text", text])
        app?.recordClipboard(
            kind: kind,
            text: text,
            imageFileName: nil,
            filePaths: [],
            sourceApp: sourceApp,
            sourceBundleID: sourceBundleID,
            hash: hash,
            byteSize: text.utf8.count
        )
    }

    private static func readImageData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) {
            return png
        }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else {
            return nil
        }
        return png
    }

    private static func classify(_ text: String) -> ClipKind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if isLink(trimmed) { return .link }
        if looksLikeCode(text) { return .code }
        return .text
    }

    private static func isLink(_ text: String) -> Bool {
        guard !text.contains("\n"), !text.contains(" ") else { return false }
        if let url = URL(string: text),
           let scheme = url.scheme?.lowercased(),
           (scheme == "http" || scheme == "https"),
           url.host != nil {
            return true
        }
        if text.lowercased().hasPrefix("www.") {
            return URL(string: "https://\(text)")?.host != nil
        }
        return false
    }

    private static func looksLikeCode(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }

        let lower = trimmed.lowercased()
        if (trimmed.hasPrefix("{") && trimmed.hasSuffix("}")) ||
            (trimmed.hasPrefix("[") && trimmed.hasSuffix("]") && trimmed.contains("{")) {
            return true
        }

        let firstWord = lower.split(whereSeparator: { $0 == " " || $0 == "\n" }).first.map(String.init) ?? ""
        let commandPrefixes: Set<String> = [
            "git", "npm", "npx", "yarn", "pnpm", "bun", "sudo", "brew", "cd", "ls", "mkdir",
            "docker", "kubectl", "python", "python3", "swift", "curl", "ssh", "scp", "make",
            "cargo", "go", "ffmpeg", "pip", "pip3", "node", "deno", "rails", "bundle", "pod",
            "systemctl", "apt", "apt-get", "chmod", "chown", "tar", "zip", "unzip", "psql",
            "mysql", "redis-cli", "aws", "gcloud", "terraform", "helm", "vite", "next"
        ]
        if !trimmed.contains("\n"), commandPrefixes.contains(firstWord) { return true }
        if trimmed.contains(" && ") || trimmed.contains(" | ") { return true }

        var score = 0
        if trimmed.contains("\n") { score += 1 }
        if trimmed.contains("{") && trimmed.contains("}") { score += 2 }
        if trimmed.contains(";") { score += 1 }
        if lower.contains("func ") || lower.contains("def ") || lower.contains("class ") || lower.contains("struct ") { score += 3 }
        if lower.contains("import ") || lower.contains("#include") || lower.contains("from ") && lower.contains(" import ") { score += 2 }
        if lower.contains("const ") || lower.contains("let ") || lower.contains("var ") { score += 1 }
        if lower.contains("=>") || lower.contains("->") || lower.contains("</") || lower.contains("#!/") { score += 2 }
        if lower.contains("return ") || lower.contains("if (") || lower.contains("for (") || lower.contains("while (") { score += 1 }
        if text.contains("\t") && trimmed.contains("\n") { score += 1 }
        if trimmed.contains("  ") && trimmed.contains("\n") { score += 1 }
        if lower.hasPrefix("select ") || lower.hasPrefix("insert into") || lower.hasPrefix("update ") { score += 3 }

        let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
        if lines.count >= 2 {
            let punctuationLines = lines.filter { line in
                let value = line.trimmingCharacters(in: .whitespaces)
                return value.hasSuffix(";") || value.hasSuffix("{") || value.hasSuffix("}") || value.hasSuffix(":")
            }
            if Double(punctuationLines.count) / Double(lines.count) > 0.5 {
                score += 2
            }
        }

        return score >= 3
    }

    private static func hash(parts: [String]) -> String {
        var hasher = SHA256()
        for part in parts {
            hasher.update(data: Data(part.utf8))
            hasher.update(data: Data([0]))
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    private static func hash(data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
